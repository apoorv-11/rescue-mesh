package com.rescuemesh.data.local

import android.content.Context
import androidx.room.Database
import androidx.room.Room
import androidx.room.RoomDatabase
import androidx.room.migration.Migration
import androidx.sqlite.db.SupportSQLiteDatabase

/**
 * On-device database. Because this is a real file-backed Room database (not
 * in-memory), every record survives an app restart — the Phase 1 gate.
 *
 * Version history:
 * - v1 (Phase 1): profile, messages, peers, metrics.
 * - v2 (Prompt 9): adds `server_ack` (verified server acknowledgements for
 *   HELLO gossip) via [MIGRATION_1_2] — the only schema change in the
 *   P5–P9 batch (contracts §6). exportSchema stays on; the schema JSON
 *   files under app/schemas are generated by the Studio/Gradle build.
 * - v3 (photo delivery, 14 Nov): adds `photo_delivery` (one receipt per
 *   record+peer whose PHOTO_ACK COMPLETE confirmed a full-photo
 *   delivery) via [MIGRATION_2_3].
 * - v4 (FIX5 + Prepare, 19 Nov): adds `photo_upload` (one receipt per
 *   record whose full photo the server accepted) and `saved_guides`
 *   (Prepare guides the user marked Saved) via [MIGRATION_3_4].
 */
@Database(
    entities = [
        ProfileEntity::class, MessageEntity::class, PeerEntity::class,
        MetricsEntity::class, ServerAckEntity::class, PhotoDeliveryEntity::class,
        PhotoUploadEntity::class, SavedGuideEntity::class
    ],
    version = 4,
    exportSchema = true
)
abstract class RescueMeshDatabase : RoomDatabase() {
    abstract fun profileDao(): ProfileDao
    abstract fun messageDao(): MessageDao
    abstract fun peerDao(): PeerDao
    abstract fun metricsDao(): MetricsDao
    abstract fun serverAckDao(): ServerAckDao
    abstract fun photoDeliveryDao(): PhotoDeliveryDao
    abstract fun photoUploadDao(): PhotoUploadDao
    abstract fun savedGuideDao(): SavedGuideDao

    companion object {
        const val DATABASE_NAME = "rescuemesh.db"

        /**
         * v1 → v2: CREATE TABLE for `server_ack`. The column definitions
         * match Room's generated schema for [ServerAckEntity] exactly
         * (TEXT/INTEGER, all NOT NULL, messageId the primary key).
         */
        val MIGRATION_1_2: Migration = object : Migration(1, 2) {
            override fun migrate(db: SupportSQLiteDatabase) {
                db.execSQL(
                    "CREATE TABLE IF NOT EXISTS `server_ack` (" +
                        "`messageId` TEXT NOT NULL, " +
                        "`status` TEXT NOT NULL, " +
                        "`issuedAt` INTEGER NOT NULL, " +
                        "`signature` TEXT NOT NULL, " +
                        "PRIMARY KEY(`messageId`))"
                )
            }
        }

        /**
         * The v3 CREATE TABLE, kept as a named constant so the migration
         * below and its JVM check share one source of truth. The column
         * definitions match Room's generated schema for
         * [PhotoDeliveryEntity] exactly (TEXT/INTEGER, all NOT NULL, the
         * (messageId, peerDeviceId) pair as composite primary key).
         */
        const val PHOTO_DELIVERY_CREATE_SQL: String =
            "CREATE TABLE IF NOT EXISTS `photo_delivery` (" +
                "`messageId` TEXT NOT NULL, " +
                "`peerDeviceId` TEXT NOT NULL, " +
                "`deliveredAt` INTEGER NOT NULL, " +
                "PRIMARY KEY(`messageId`, `peerDeviceId`))"

        /** v2 → v3: CREATE TABLE for `photo_delivery` (see [PHOTO_DELIVERY_CREATE_SQL]). */
        val MIGRATION_2_3: Migration = object : Migration(2, 3) {
            override fun migrate(db: SupportSQLiteDatabase) {
                db.execSQL(PHOTO_DELIVERY_CREATE_SQL)
            }
        }

        /** The v4 CREATE TABLEs, kept as named constants so the migration and its JVM check share one source of truth. */
        const val PHOTO_UPLOAD_CREATE_SQL: String =
            "CREATE TABLE IF NOT EXISTS `photo_upload` (" +
                "`messageId` TEXT NOT NULL, " +
                "`uploadedAt` INTEGER NOT NULL, " +
                "PRIMARY KEY(`messageId`))"
        const val SAVED_GUIDES_CREATE_SQL: String =
            "CREATE TABLE IF NOT EXISTS `saved_guides` (" +
                "`guideId` TEXT NOT NULL, " +
                "`savedAt` INTEGER NOT NULL, " +
                "PRIMARY KEY(`guideId`))"

        /** v3 → v4: CREATE TABLE for `photo_upload` and `saved_guides`. */
        val MIGRATION_3_4: Migration = object : Migration(3, 4) {
            override fun migrate(db: SupportSQLiteDatabase) {
                db.execSQL(PHOTO_UPLOAD_CREATE_SQL)
                db.execSQL(SAVED_GUIDES_CREATE_SQL)
            }
        }

        fun create(context: Context): RescueMeshDatabase =
            Room.databaseBuilder(context.applicationContext, RescueMeshDatabase::class.java, DATABASE_NAME)
                .addMigrations(MIGRATION_1_2, MIGRATION_2_3, MIGRATION_3_4)
                .build()
    }
}
